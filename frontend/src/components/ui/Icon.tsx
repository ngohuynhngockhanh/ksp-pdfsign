export type IconName = keyof typeof ICON_MAP;

export const ICON_NAMES = Object.keys(ICON_MAP) as IconName[];

export interface AppIconProps {
  name: IconName;
  size?: number;
  strokeWidth?: number;
  className?: string;
  "aria-hidden"?: boolean;
  "aria-label"?: string;
}

export function AppIcon({
  name,
  size = 16,
  strokeWidth = 1.8,
  className = "",
  "aria-hidden": ariaHidden,
  "aria-label": ariaLabel,
}: AppIconProps) {
  const IconComponent = ICON_MAP[name];
  const cls = className ? `ui-icon ${className}` : "ui-icon";

  if (ariaLabel) {
    return (
      <IconComponent
        size={size}
        strokeWidth={strokeWidth}
        className={cls}
        role="img"
        aria-label={ariaLabel}
        aria-hidden={ariaHidden ?? false}
        focusable="false"
      />
    );
  }

  return (
    <IconComponent
      size={size}
      strokeWidth={strokeWidth}
      className={cls}
      aria-hidden={ariaHidden ?? true}
      focusable="false"
    />
  );
}
